// Rebuilds data/publications-snapshot.js from the live ORCID record (+ OpenAlex).
// Run locally with:  node scripts/update-publications.mjs
// Runs nightly on GitHub via .github/workflows/update-publications.yml.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const root = new URL("..", import.meta.url);
const context = { console, fetch, encodeURIComponent, URL, setTimeout };
context.window = context;
context.globalThis = context;
vm.createContext(context);
for (const file of ["publications-config.js", "publications-core.js"]) {
  vm.runInContext(readFileSync(new URL(file, root), "utf8"), context, { filename: file });
}

const records = await context.PublicationsCore.fetchRecords(context.PUBLICATION_CONFIG, fetch);
if (!records.length) throw new Error("ORCID returned no works; snapshot left unchanged.");

const outPath = new URL("data/publications-snapshot.js", root);
const previous = (() => {
  try {
    return readFileSync(outPath, "utf8");
  } catch {
    return "";
  }
})();
const recordsJson = JSON.stringify(records, null, 1);
if (previous.includes(recordsJson)) {
  console.log(`No change (${records.length} works).`);
} else {
  const body =
    "// Generated by scripts/update-publications.mjs. Do not edit by hand.\n" +
    `window.PUBLICATION_SNAPSHOT = {\n"generatedAt": ${JSON.stringify(new Date().toISOString())},\n"records": ${recordsJson}\n};\n`;
  writeFileSync(outPath, body);
  console.log(`Wrote ${records.length} works.`);
}
